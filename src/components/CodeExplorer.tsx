import React, { useState, useMemo } from 'react';
import JSZip from 'jszip';
import { kmpCodebase } from '../data/kmpCodebase';
import { KMPFile } from '../types';
import { Folder, File, Download, Search, Copy, Check, Info } from 'lucide-react';

export default function CodeExplorer() {
  const [selectedFile, setSelectedFile] = useState<KMPFile>(kmpCodebase[4]); // default to SoundPlayer.kt (common)
  const [searchQuery, setSearchQuery] = useState('');
  const [copied, setCopied] = useState(false);
  const [isExporting, setIsExporting] = useState(false);

  // Group files into categories for easy browsing
  const categorizedFiles = useMemo(() => {
    const categories: { [key: string]: KMPFile[] } = {
      'Shared UI & Logic (commonMain)': [],
      'Android Core (androidMain)': [],
      'iOS Native Integration (iosMain)': [],
      'Desktop JVM (desktopMain)': [],
      'Project Configuration (Gradle)': [],
    };

    kmpCodebase.forEach(file => {
      if (file.path.startsWith('shared/src/commonMain')) {
        categories['Shared UI & Logic (commonMain)'].push(file);
      } else if (file.path.startsWith('shared/src/androidMain') || file.path.startsWith('androidApp')) {
        categories['Android Core (androidMain)'].push(file);
      } else if (file.path.startsWith('shared/src/iosMain') || file.path.startsWith('iosApp')) {
        categories['iOS Native Integration (iosMain)'].push(file);
      } else if (file.path.startsWith('shared/src/desktopMain')) {
        categories['Desktop JVM (desktopMain)'].push(file);
      } else {
        categories['Project Configuration (Gradle)'].push(file);
      }
    });

    return categories;
  }, []);

  const handleCopy = () => {
    navigator.clipboard.writeText(selectedFile.content);
    setCopied(true);
    setTimeout(() => setCopied(false), 2000);
  };

  const handleExportZip = async () => {
    setIsExporting(true);
    try {
      const zip = new JSZip();

      // Create standard project structure and insert all files
      kmpCodebase.forEach(file => {
        zip.file(file.path, file.content);
      });

      // Include a useful README
      const readmeContent = `# Villager Hmm - Kotlin Multiplatform (KMP) Mobile App

This project was generated by Google AI Studio. It is a Kotlin Multiplatform (KMP) mobile and desktop application featuring Compose Multiplatform for shared UI.

## Structure

- \`shared/\`: Common shared code built with Compose Multiplatform.
  - \`src/commonMain/\`: Shared UI, colors, custom Villager Nose Button, and background canvas.
  - \`src/androidMain/\`: Android-specific low-latency SoundPool player implementation.
  - \`src/iosMain/\`: iOS-specific AVAudioPlayer sound player implementation.
  - \`src/desktopMain/\`: Desktop-specific javax.sound audio player implementation.
- \`androidApp/\`: Native Android application launcher.
- \`iosApp/\`: Native Xcode project files to launch the iOS app.

## Requirements

- Android Studio / IntelliJ IDEA (latest versions)
- Kotlin 1.9.20+
- JDK 17
- Xcode (for running iOS apps on Mac)

## How to Run

1. Open the root folder in **Android Studio Koala** or newer.
2. Let Gradle sync and download all dependencies.
3. Select \`androidApp\` from the run configuration dropdown and press **Run** to launch the Android emulator.
4. For iOS, open \`iosApp/iosApp.xcodeproj\` in Xcode or use Kotlin Multiplatform Mobile plugin in Android Studio.
`;
      zip.file('README.md', readmeContent);

      // Generate the zip file asynchronously
      const blob = await zip.generateAsync({ type: 'blob' });
      
      // Trigger browser download
      const url = URL.createObjectURL(blob);
      const link = document.createElement('a');
      link.href = url;
      link.download = 'VillagerHmm_KMP_Project.zip';
      document.body.appendChild(link);
      link.click();
      document.body.removeChild(link);
      URL.revokeObjectURL(url);
    } catch (error) {
      console.error('Failed to generate ZIP:', error);
    } finally {
      setIsExporting(false);
    }
  };

  // Simple token-based highlighter for kotlin/gradle/xml code
  const renderHighlightedCode = (content: string, lang: string) => {
    const lines = content.split('\n');
    return lines.map((line, idx) => {
      // Very basic highlighter for styling keywords
      let renderedLine = line;
      if (lang === 'kotlin' || lang === 'swift') {
        renderedLine = line
          .replace(/\b(package|import|class|interface|expect|actual|fun|val|var|private|override|constructor|return|try|catch|is|true|false|listOf|forEach|remember|mutableStateOf|by|get|set|when|if|else)\b/g, '<span class="text-amber-500 font-semibold">$1</span>')
          .replace(/\b(AppTheme|VillagerNoseButton|VillageBackground|SoundPlayer|Box|Column|Row|Text|IconButton|Canvas|Modifier|Color|Size|Offset|AudioAttributes|SoundPool|AVAudioPlayer|AudioSystem|Clip)\b/g, '<span class="text-cyan-400">$1</span>')
          .replace(/("[^"]*")/g, '<span class="text-emerald-400">$1</span>')
          .replace(/(\/\/.*)/g, '<span class="text-zinc-500 italic">$1</span>');
      } else if (lang === 'xml') {
        renderedLine = line
          .replace(/(&lt;[^&]*&gt;)/g, '<span class="text-amber-400">$1</span>')
          .replace(/("[^"]*")/g, '<span class="text-emerald-400">$1</span>')
          .replace(/(&lt;!--.*--&gt;)/g, '<span class="text-zinc-500 italic">$1</span>');
      } else {
        // Properties or standard configs
        renderedLine = line
          .replace(/(=.*)/g, '<span class="text-emerald-400">$1</span>')
          .replace(/(#.*)/g, '<span class="text-zinc-500 italic">$1</span>');
      }

      return (
        <div key={idx} className="table-row">
          <span className="table-cell text-zinc-600 text-right pr-4 select-none w-8 text-xs">{idx + 1}</span>
          <span className="table-cell whitespace-pre font-mono text-xs text-zinc-100" dangerouslySetInnerHTML={{ __html: renderedLine || '&nbsp;' }} />
        </div>
      );
    });
  };

  // Filter files by query
  const filteredCategories = useMemo(() => {
    if (!searchQuery) return categorizedFiles;
    const lowerQuery = searchQuery.toLowerCase();
    const filtered: { [key: string]: KMPFile[] } = {};

    Object.keys(categorizedFiles).forEach(cat => {
      const matched = categorizedFiles[cat].filter(
        f => f.name.toLowerCase().includes(lowerQuery) || f.path.toLowerCase().includes(lowerQuery)
      );
      if (matched.length > 0) {
        filtered[cat] = matched;
      }
    });

    return filtered;
  }, [searchQuery, categorizedFiles]);

  return (
    <div className="flex flex-col lg:flex-row h-full rounded-sm overflow-hidden bg-black border-4 border-white shadow-[8px_8px_0px_0px_rgba(255,255,255,0.05)]" id="code-explorer-section">
      
      {/* File Tree Sidebar */}
      <div className="w-full lg:w-80 flex flex-col border-b lg:border-b-0 lg:border-r-4 border-white bg-zinc-950 p-4">
        <div className="flex items-center justify-between mb-4">
          <h3 className="font-courier text-xs font-bold tracking-widest text-white flex items-center gap-2 uppercase">
            📂 PROJECT FILES
          </h3>
          <button
            onClick={handleExportZip}
            disabled={isExporting}
            className="flex items-center gap-1 text-[9px] font-courier font-bold bg-[#55aa33] hover:bg-[#68be44] active:bg-[#3d7a24] disabled:bg-zinc-800 text-white px-2.5 py-1.5 border-2 border-white rounded-sm transition cursor-pointer uppercase shadow-[2px_2px_0px_rgba(255,255,255,0.15)]"
            title="Download full KMP project with Gradle configurations as a ZIP file"
          >
            <Download className="w-3.5 h-3.5" />
            {isExporting ? 'PACKING...' : 'EXPORT ZIP'}
          </button>
        </div>

        {/* Search */}
        <div className="relative mb-4">
          <Search className="w-4 h-4 absolute left-2.5 top-2.5 text-zinc-500" />
          <input
            type="text"
            placeholder="Search KMP codebase..."
            value={searchQuery}
            onChange={e => setSearchQuery(e.target.value)}
            className="w-full bg-black text-xs text-white pl-9 pr-3 py-2 border-2 border-zinc-800 rounded-sm focus:outline-none focus:border-white font-courier"
          />
        </div>

        {/* Categories / Directories */}
        <div className="flex-1 overflow-y-auto minecraft-scroll pr-1 space-y-4 max-h-[300px] lg:max-h-none">
          {Object.keys(filteredCategories).map(category => (
            <div key={category} className="space-y-1">
              <div className="flex items-center gap-1.5 text-zinc-300 font-courier font-bold text-xs uppercase tracking-wider">
                <Folder className="w-3.5 h-3.5 text-[#7297ff] shrink-0" />
                <span className="truncate">{category}</span>
              </div>
              <div className="pl-3 space-y-1">
                {filteredCategories[category].map(file => {
                  const isSelected = selectedFile.path === file.path;
                  return (
                    <button
                      key={file.path}
                      onClick={() => setSelectedFile(file)}
                      className={`w-full flex items-center gap-2 text-left px-2 py-1.5 rounded-sm text-xs transition font-courier ${
                        isSelected 
                          ? 'bg-white text-black font-bold border-2 border-black' 
                          : 'text-zinc-400 hover:bg-zinc-900 hover:text-white'
                      }`}
                    >
                      <File className={`w-3.5 h-3.5 shrink-0 ${isSelected ? 'text-black' : 'text-zinc-500'}`} />
                      <span className="truncate" title={file.path}>{file.name}</span>
                    </button>
                  );
                })}
              </div>
            </div>
          ))}

          {Object.keys(filteredCategories).length === 0 && (
            <div className="text-center py-6 text-zinc-600 text-xs font-courier">
              No matching KMP files found
            </div>
          )}
        </div>
      </div>

      {/* Code Viewer Panel */}
      <div className="flex-1 flex flex-col min-w-0 bg-black">
        
        {/* Header Bar */}
        <div className="flex items-center justify-between px-4 py-3 bg-black border-b-4 border-white">
          <div className="flex flex-col min-w-0">
            <span className="text-zinc-500 text-[9px] font-courier tracking-wider truncate">
              {selectedFile.path.substring(0, selectedFile.path.lastIndexOf('/') + 1)}
            </span>
            <span className="text-white font-courier text-xs font-bold uppercase tracking-wider truncate">
              {selectedFile.name}
            </span>
          </div>

          <button
            onClick={handleCopy}
            className="flex items-center gap-1.5 text-white hover:bg-zinc-900 bg-black border-2 border-white px-3 py-1.5 rounded-sm text-xs transition font-courier font-bold uppercase tracking-wider cursor-pointer shrink-0 active:translate-y-0.5"
          >
            {copied ? (
              <>
                <Check className="w-3.5 h-3.5 text-[#55aa33]" />
                <span className="text-[#55aa33]">Copied!</span>
              </>
            ) : (
              <>
                <Copy className="w-3.5 h-3.5" />
                <span>Copy Code</span>
              </>
            )}
          </button>
        </div>

        {/* Info panel explaining what this file does */}
        <div className="bg-white/5 border-b-2 border-white/10 px-4 py-3.5 flex items-start gap-3 text-zinc-300 text-xs font-courier">
          <Info className="w-4 h-4 text-[#7297ff] shrink-0 mt-0.5" />
          <div>
            <span className="font-bold text-[#7297ff] text-[11px] uppercase tracking-wider block mb-0.5">
              {selectedFile.path.includes('commonMain') && 'Shared Code: Runs on Android, iOS & Desktop JVM!'}
              {selectedFile.path.includes('androidMain') && 'Android Specific actual implementation: High-performance SoundPool.'}
              {selectedFile.path.includes('iosMain') && 'iOS Specific actual implementation: Native AVAudioPlayer loader.'}
              {selectedFile.path.includes('desktopMain') && 'Desktop Specific actual implementation: JVM Clip player.'}
              {selectedFile.path.startsWith('androidApp') && 'Android App wrapper: Launches common Compose UI.'}
              {selectedFile.path.startsWith('iosApp') && 'iOS App wrapper: Connects Xcode/SwiftUI with Kotlin Controller.'}
              {(!selectedFile.path.includes('Main') && !selectedFile.path.includes('App')) && 'Root Build Setup: gradle setups.'}
            </span>
            <p className="text-zinc-500 leading-relaxed">
              {selectedFile.path.includes('commonMain') && 'Define UI styles and layouts here once; they compile to multiple platforms.'}
              {selectedFile.path.includes('androidMain') && 'Handles context-dependent SoundPool mapping, loading raw assets instantly.'}
              {selectedFile.path.includes('iosMain') && 'Loads bundles directly inside iOS sandbox using Apple’s NSBundle system.'}
              {selectedFile.path.includes('desktopMain') && 'Synthesizes sound streams directly into system sound mixers.'}
            </p>
          </div>
        </div>

        {/* Code Block Container */}
        <div className="flex-1 overflow-auto minecraft-scroll p-5 bg-zinc-950 font-mono min-h-[300px] max-h-[500px] lg:max-h-none">
          <div className="table w-full border-collapse">
            {renderHighlightedCode(selectedFile.content, selectedFile.language)}
          </div>
        </div>
      </div>
    </div>
  );
}
